#!/usr/bin/env node
// Bundles the internal docs (../docs/**/*.md, outside web/) into src/content/admin-docs.generated.ts, so /admin/docs
// renders them from the build itself: Vercel builds from web/ and may not have the repo's other folders. Runs before
// `next dev` and `next build`; when ../docs is missing (a web/-only checkout) it keeps the committed file as it is.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(web, '..', 'docs');
const out = join(web, 'src', 'content', 'admin-docs.generated.ts');

if (!existsSync(src)) {
  console.log(`sync-docs: ${src} not found; keeping ${relative(web, out)}`);
  process.exit(0);
}

const walk = (dir) => readdirSync(dir).sort().flatMap((name) => {
  const p = join(dir, name);
  return statSync(p).isDirectory() ? walk(p) : name.endsWith('.md') ? [p] : [];
});

const docs = walk(src).map((file) => {
  const path = relative(src, file).split(sep).join('/');
  const body = readFileSync(file, 'utf8');
  const title = body.match(/^#\s+(.+)$/m)?.[1].trim() ?? path;
  // The first paragraph after the title, as plain text: the index's one-line summary.
  const para = body.replace(/^#\s+.+$/m, '').split(/\n\s*\n/).map((s) => s.trim()).find((s) => s && !/^[#|>`-]/.test(s)) ?? '';
  const plain = para.replace(/\s+/g, ' ').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/[*`]/g, '');
  const summary = plain.length > 220 ? `${plain.slice(0, 217).replace(/\s+\S*$/, '')}…` : plain;
  const group = path.includes('/') ? path.split('/')[0] : '';
  return { slug: path.replace(/\.md$/, '').replace(/\//g, '-'), path, group, title, summary, body };
});

const text = `// Generated by scripts/sync-docs.mjs from ../docs/**/*.md. Do not edit: change the markdown and rebuild.
export interface AdminDoc { slug: string; path: string; group: string; title: string; summary: string; body: string }

export const ADMIN_DOCS: AdminDoc[] = ${JSON.stringify(docs, null, 2)};
`;
mkdirSync(dirname(out), { recursive: true });
const before = existsSync(out) ? readFileSync(out, 'utf8') : '';
if (before !== text) writeFileSync(out, text);
console.log(`sync-docs: ${docs.length} docs ${before === text ? 'unchanged' : 'written'} (${relative(web, out)})`);
