/**
 * Generate agent/lib/workflow-library.generated.ts from the library the deployment profile names.
 *
 * Base code ships NO workflow and NO recipe of its own. What a new workspace is provisioned with is the content of
 * the directories listed under `library.sources` in profiles/*.json (scripts/lib/profile-library.mjs): none in the
 * default profile, so the committed file is empty; a deployment opts into one by adding a profile file, and a
 * subagent pack ships its own beside its specialists. See docs/DEPLOYMENT_PROFILE.md, "library".
 *
 * The library has to be reachable from TWO places: the CLI (`operator:new-org`,
 * `operator:seed-workflows`), which could read the files off disk, and
 * the web onboarding route, which cannot — a Next serverless function only
 * ships what the bundler traced, and a runtime readdir of a directory
 * finds nothing there. Baking the library into a module makes both paths use
 * the same bytes.
 *
 * Run:  npm run build:workflow-library   (and after editing a library file or `library.sources`)
 *       node scripts/build-workflow-library.mjs --print   the module on stdout, nothing written (tests)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { librarySources, readLibrary } from "./lib/profile-library.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(root, "agent", "lib", "workflow-library.generated.ts");

let library;
try {
  library = readLibrary(root, librarySources(root));
} catch (e) {
  console.error(`build-workflow-library: ${e.message}`);
  process.exit(1);
}
const { sources, workflows, recipes } = library;

const body = `// GENERATED by scripts/build-workflow-library.mjs — do not edit by hand.
// Source: the deployment profile's library.sources (${sources.length ? sources.join(", ") : "none"}): ${workflows.length} workflows, ${recipes.length} recipes
//
// Regenerate with: npm run build:workflow-library

export interface LibraryWorkflow {
  readonly name: string;
  readonly description: string;
  readonly steps: readonly string[];
  readonly script: string;
}

export interface LibraryRecipe {
  readonly slug: string;
  readonly title: string;
  readonly summary: string | null;
  /** The workspace health check this recipe turns green, when it has one. */
  readonly satisfiesCheck: string | null;
}

/** The ids under the profile's library.sources this file was built from. Empty: this deployment provisions no library. */
export const LIBRARY_SOURCES: readonly string[] = ${JSON.stringify(sources)};

export const WORKFLOW_LIBRARY: readonly LibraryWorkflow[] = ${JSON.stringify(workflows, null, 2)} as const;

export const RECIPE_LIBRARY: readonly LibraryRecipe[] = ${JSON.stringify(recipes, null, 2)} as const;
`;

if (process.argv.includes("--print")) {
  process.stdout.write(body);
} else {
  writeFileSync(out, body);
  console.log(`✓ wrote ${out} (${sources.length ? sources.join(", ") : "no library source"}: ${workflows.length} workflows, ${recipes.length} recipes)`);
}
