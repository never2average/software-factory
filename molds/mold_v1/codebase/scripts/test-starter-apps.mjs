/**
 * STARTER APPS ARE A LIBRARY'S, AND THE BUILD REFUSES ONE THAT COULD NOT WORK. Offline.
 *
 * A starter app is an app every new workspace of a deployment is created with. Like workflows and recipes it is
 * named by the deployment profile's library (`<library>/apps.json` or `<library>/apps/*.json`), never by base code.
 * This holds the rules that need no database (scripts/test-starter-apps-db.mjs holds the rest, through the routes):
 *
 *   1. the default profile ships none, and the committed generated library is empty;
 *   2. the opt-in library (library/account-delivery) ships three, each generated by a specialist the base has;
 *   3. the build refuses a starter app it could not generate or should not carry, naming the file and the fix: a
 *      source that is not a specialist of the build, one the profile excludes, a workflow of another library, a
 *      workflow the build does not provision, a duplicate key or name, a secret-looking string, a bad schedule;
 *   4. what a workspace receives is in the profile's words, and never an app whose source it does not have;
 *   5. the cleanup's rules for a starter app (removable while untouched, kept once edited, opened or refreshed);
 *   6. the wiring that keeps the promises: an idempotent insert, a first open that asks once, an existing workspace
 *      left alone, the column in the schema and in the migration journal.
 *
 * On the commit before this change it fails at the first import (readStarterApps does not exist).
 *
 *   npm run test:starter-apps
 */
