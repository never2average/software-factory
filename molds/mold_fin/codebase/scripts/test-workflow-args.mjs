import { validateWorkflowArgs, coerceWorkflowArgs, argKeysRead } from "../lib/workflow-args.ts";
let pass = 0, fail = 0;
const t = (name, cond) => { if (cond) { pass++; } else { fail++; console.log("  FAIL", name); } };

const renewal = `const focus = args && args.customerId ? x : null; if (args.dryRun) {}`;
t("reads customerId + dryRun", [...(argKeysRead(renewal) ?? [])].sort().join(",") === "customerId,dryRun");
t("correct payload passes", validateWorkflowArgs(renewal, { customerId: "acme" }) === null);
t("near-miss key is refused", /never reads "customer"/.test(validateWorkflowArgs(renewal, { customer: "acme" })?.message ?? ""));
t("…and says what it does read", (validateWorkflowArgs(renewal, { customer: "x" })?.expected ?? []).includes("customerId"));
t("missing keys are fine", validateWorkflowArgs(renewal, {}) === null);
t("array refused", /must be a JSON object/.test(validateWorkflowArgs(renewal, ["a"])?.message ?? ""));
t("string refused", /must be a JSON object/.test(validateWorkflowArgs(renewal, "acme")?.message ?? ""));
t("no-args script refuses a payload", /reads no arguments/.test(validateWorkflowArgs("const x = 1;", { a: 1 })?.message ?? ""));
t("dynamic access is not judged", validateWorkflowArgs("const k = args[key];", { anything: 1 }) === null);
t("comment mention does not count", (argKeysRead("// args.ghost\nconst a = args.real;") ?? new Set()).has("ghost") === false);
t("bad JSON string fails with the parser message", /not valid JSON/.test(coerceWorkflowArgs("{nope").error ?? ""));
t("good JSON string parses", coerceWorkflowArgs('{"customerId":"acme"}').args?.customerId === "acme");
t("object passes through", coerceWorkflowArgs({ a: 1 }).args?.a === 1);
t("empty string is no args", coerceWorkflowArgs("  ").args === undefined);
console.log(`workflow args: ${pass}/${pass + fail} checks passed`);
process.exit(fail ? 1 : 0);
