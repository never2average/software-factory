/**
 * Generate agent/lib/workflow-library.generated.ts from scripts/fde/workflows/.
 *
 * The library has to be reachable from TWO places: the CLI (`fde:new-org`,
 * `fde:seed-workflows`), which can read the .workflow.js files off disk, and
 * the web onboarding route, which cannot — a Next serverless function only
 * ships what the bundler traced, and a runtime readdir of a scripts/ directory
 * finds nothing there. Baking the library into a module makes both paths use
 * the same bytes.
 *
 * Run:  npm run build:workflow-library   (and after editing any .workflow.js)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "fde", "workflows");
const out = join(here, "..", "agent", "lib", "workflow-library.generated.ts");

const items = readdirSync(src)
  .filter((f) => f.endsWith(".workflow.js"))
  .sort()
  .map((f) => {
    const script = readFileSync(join(src, f), "utf8");
    const name = /name:\s*"([^"]+)"/.exec(script)?.[1];
    const description = /description:\s*"([^"]+)"/.exec(script)?.[1];
    const steps = [...script.matchAll(/phase\("([^"]+)"\)/g)].map((m) => m[1]);
    if (!name || !description) throw new Error(`${f}: missing name/description in meta`);
    return { name, description, steps, script };
  });

const body = `// GENERATED by scripts/build-workflow-library.mjs — do not edit by hand.
// Source: scripts/fde/workflows/*.workflow.js  (${items.length} workflows)
//
// Regenerate with: npm run build:workflow-library

export interface LibraryWorkflow {
  readonly name: string;
  readonly description: string;
  readonly steps: readonly string[];
  readonly script: string;
}

export const WORKFLOW_LIBRARY: readonly LibraryWorkflow[] = ${JSON.stringify(items, null, 2)} as const;
`;

writeFileSync(out, body);
console.log(`✓ wrote ${out} (${items.length} workflows)`);
